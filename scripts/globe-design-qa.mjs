 const clickCell=async id=>{const p=await page.evaluate(id=>window.geodesicQA.screen(id),id);if(mobile)await page.touchscreen.tap(p.x,p.y);else await page.mouse.click(p.x,p.y);};
 const initial=await page.evaluate(()=>window.geodesicQA.state().design);
 await page.locator('#editHexMode').click();await page.locator('#areaBrush').fill('2');
 await clickCell(initial[0]);await page.waitForFunction(()=>window.geodesicQA.state().design.length>1);
 const ids=await page.evaluate(()=>window.geodesicQA.state().design);
 await page.locator('#paintCells').click();await clickCell(initial[0]);await page.locator('#undoPaint').click();
